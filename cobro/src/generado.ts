/**
 * Money helpers shared by the server-rendered price cards and the checkout script.
 * Amounts are USD. Since 2026-10-21 the 7 % is INCLUDED in the price of tests and consultations
 * (Mari and Verónica: «a todos los precios se les suma el 7 %», rounded to the dollar), so no type
 * carries tax on top: the checkout's tax row hides itself at 0 and Klarna adds no tax line.
 */
export const TAX_RATE = 0.07;

export const TIPOS_CON_IMPUESTO: readonly string[] = [];

export const conImpuesto = (tipo: string | undefined): boolean =>
  !!tipo && TIPOS_CON_IMPUESTO.includes(tipo);

export const impuestoCentavos = (baseCentavos: number): number =>
  Math.round(baseCentavos * TAX_RATE);

/** Round to cents the way the prototype did it (`Math.round(x * 100) / 100`). */
export function redondear(n: number): number {
  return Math.round(n * 100) / 100;
}

export interface Desglose {
  subtotal: number;
  impuesto: number;
  total: number;
  taxRate: number;
}

export function desglose(subtotal: number, taxRate = 0): Desglose {
  const impuesto = redondear(subtotal * taxRate);
  const total = redondear(subtotal + impuesto);
  return { subtotal, impuesto, total, taxRate };
}

export function usd(n: number): string {
  return `$${n.toFixed(2)}`;
}

export const precioOferta = (centavos: number, descuento: number): number =>
  Math.round((centavos * (100 - descuento)) / 100);

export const DESCUENTO_BLACK_FRIDAY = 20;

export function desdeCentavos(centavos: number): number {
  return centavos / 100;
}

export function aCentavos(monto: number): number {
  return Math.round(monto * 100);
}

export interface OfertaGuia {
  guia: string;
  oferta: string;
}

export interface CambioCampana {
  de: string;
  a: string;
  descuento?: number;
}

export interface Campana {
  codigo: string;
  inicio: string;
  fin: string;
  cambios: CambioCampana[];
  regalo?: string;
}

export interface Catalogo {
  vendibles: string[];
  examenes: string[];
  guias: string[];
  cargo: string;
  ofertas: OfertaGuia[];
  campanas?: Campana[];
}

export function campanaActiva<T extends Pick<Campana, 'codigo' | 'inicio' | 'fin'>>(
  campanas: readonly T[] | undefined,
  cupon: string,
  ahora: Date
): T | null {
  const codigo = cupon.trim().toUpperCase();
  const t = ahora.getTime();
  return (
    campanas?.find(
      (c) => c.codigo === codigo && Date.parse(c.inicio) <= t && t < Date.parse(c.fin)
    ) ?? null
  );
}

export const productosDeCampana = (campanas: readonly Campana[] | undefined): string[] =>
  (campanas ?? []).flatMap((c) => c.cambios.map((cambio) => cambio.a));

export interface Linea {
  producto: string;
  cantidad: number;
}

const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export function leerItems(texto: string): Linea[] {
  return texto
    .split(',')
    .map((parte) => parte.trim().split(':')[0])
    .filter((producto) => SLUG.test(producto))
    .map((producto) => ({ producto, cantidad: 1 }));
}

export function escribirItems(lineas: Linea[]): string {
  return lineas
    .map((l) => (l.cantidad === 1 ? l.producto : `${l.producto}:${l.cantidad}`))
    .join(',');
}

export function ofertaDisponible(productos: string[], catalogo: Catalogo): OfertaGuia | null {
  const hayGuia = productos.some((p) => catalogo.guias.includes(p));
  if (!hayGuia) return null;
  return catalogo.ofertas.find((o) => !productos.includes(o.guia)) ?? null;
}

